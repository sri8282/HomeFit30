import { ExercisePose, FigurePosture } from './ExerciseFigure';

export interface ExerciseKeyframeDef {
  id: string;
  name: string;
  targetArea: string;
  posture: FigurePosture;
  hasDumbbell: boolean;
  keyframes: ExercisePose[];
  duration?: number; // Duration in seconds per rep (default: 2.0s)
}

/**
 * Interpolates smoothly between two numbers.
 */
function lerp(a: number, b: number, t: number): number {
  return a + (b - a) * t;
}

/**
 * Interpolates between two poses.
 */
export function interpolatePose(poseA: ExercisePose, poseB: ExercisePose, t: number): ExercisePose {
  const clampT = Math.max(0, Math.min(1, t));

  // Determine root positions
  const hipX =
    poseA.hipX !== undefined && poseB.hipX !== undefined
      ? lerp(poseA.hipX, poseB.hipX, clampT)
      : poseA.hipX !== undefined
      ? poseA.hipX
      : poseB.hipX;

  const hipY =
    poseA.hipY !== undefined && poseB.hipY !== undefined
      ? lerp(poseA.hipY, poseB.hipY, clampT)
      : poseA.hipY !== undefined
      ? poseA.hipY
      : poseB.hipY;

  return {
    posture: poseA.posture || poseB.posture,
    hasDumbbell: poseA.hasDumbbell !== undefined ? poseA.hasDumbbell : poseB.hasDumbbell,
    hipX,
    hipY,
    torsoAngle: lerp(poseA.torsoAngle, poseB.torsoAngle, clampT),
    neckAngle: lerp(poseA.neckAngle || 0, poseB.neckAngle || 0, clampT),

    leftShoulderAngle: lerp(poseA.leftShoulderAngle, poseB.leftShoulderAngle, clampT),
    leftElbowAngle: lerp(poseA.leftElbowAngle, poseB.leftElbowAngle, clampT),

    rightShoulderAngle:
      poseA.rightShoulderAngle !== undefined && poseB.rightShoulderAngle !== undefined
        ? lerp(poseA.rightShoulderAngle, poseB.rightShoulderAngle, clampT)
        : undefined,
    rightElbowAngle:
      poseA.rightElbowAngle !== undefined && poseB.rightElbowAngle !== undefined
        ? lerp(poseA.rightElbowAngle, poseB.rightElbowAngle, clampT)
        : undefined,

    leftHipAngle: lerp(poseA.leftHipAngle, poseB.leftHipAngle, clampT),
    leftKneeAngle: lerp(poseA.leftKneeAngle, poseB.leftKneeAngle, clampT),

    rightHipAngle:
      poseA.rightHipAngle !== undefined && poseB.rightHipAngle !== undefined
        ? lerp(poseA.rightHipAngle, poseB.rightHipAngle, clampT)
        : undefined,
    rightKneeAngle:
      poseA.rightKneeAngle !== undefined && poseB.rightKneeAngle !== undefined
        ? lerp(poseA.rightKneeAngle, poseB.rightKneeAngle, clampT)
        : undefined,
  };
}

/**
 * Interpolates across a multi-keyframe sequence looping smoothly.
 * For 2 keyframes: A -> B -> A.
 * For 3 keyframes: A -> B -> C -> A.
 */
export function interpolateSequence(keyframes: ExercisePose[], progress: number): ExercisePose {
  if (!keyframes || keyframes.length === 0) {
    return {
      torsoAngle: -90,
      leftShoulderAngle: 90,
      leftElbowAngle: 90,
      leftHipAngle: 90,
      leftKneeAngle: 90,
    };
  }

  if (keyframes.length === 1) return keyframes[0];

  // Construct cyclic loop
  // e.g. [A, B] becomes [A, B, A]
  // e.g. [A, B, C] becomes [A, B, C, A]
  const loopList = [...keyframes, keyframes[0]];
  const totalSegments = loopList.length - 1;

  // Normalized progress in [0, totalSegments)
  const norm = ((progress % totalSegments) + totalSegments) % totalSegments;
  const segmentIdx = Math.floor(norm);
  const localT = norm - segmentIdx;

  const currentPose = loopList[segmentIdx];
  const nextPose = loopList[segmentIdx + 1];

  return interpolatePose(currentPose, nextPose, localT);
}

